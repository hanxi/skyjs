#!/usr/bin/env node
"use strict";

// Generates native-registry.c for a static (mobile) build: scans the packages
// to be linked in and emits the table read by skynetcore.native.initStatic().
// Symbols are alias-renamed per package at compile time
// (-Dskyjs_ext_init=skyjs_ext_init_<pkg>), so the table entries point at the
// renamed names and multiple extensions can coexist in one symbol space.
//
// Usage:
//   node tools/gen-native-registry.js --out build/native-registry.c \
//        [--pkg @skyjs/example-native=./node_modules/@skyjs/example-native]
//
// With no --pkg options the output is an empty table (the dynamic-build case).

const fs = require("fs");
const path = require("path");

function sanitize(name) {
    return name.replace(/^@/, "").replace(/[^A-Za-z0-9_]/g, "_");
}

function parseArgs(argv) {
    const out = { out: null, pkgs: [] };
    for (let i = 0; i < argv.length; i++) {
        if (argv[i] === "--out") out.out = argv[++i];
        else if (argv[i] === "--pkg") out.pkgs.push(argv[++i]);
    }
    return out;
}

function main() {
    const { out, pkgs } = parseArgs(process.argv.slice(2));
    if (!out) {
        process.stderr.write("usage: gen-native-registry.js --out <file> [--pkg name=dir ...]\n");
        process.exit(1);
    }

    const entries = pkgs.map((spec) => {
        const eq = spec.indexOf("=");
        const name = eq < 0 ? spec : spec.slice(0, eq);
        return { name, symbol: sanitize(name) };
    });

    const externs = entries.map((e) => `
extern int skyjs_ext_abi_${e.symbol}(void);
extern JSValue skyjs_ext_init_${e.symbol}(JSContext *ctx, JSValueConst ns);
`).join("");
    const rows = entries.map((e) =>
        `\t{ ${JSON.stringify(e.name)}, skyjs_ext_abi_${e.symbol}, skyjs_ext_init_${e.symbol} },`
    ).join("\n");

    const body = `/* Generated by tools/gen-native-registry.js -- do not edit. */
#include "skyjs-native-registry.h"
${externs}
static const struct skyjs_static_ext skyjs_static_exts[] = {
${rows}
};

int
skyjs_native_static_count(void) {
\treturn (int)(sizeof(skyjs_static_exts) / sizeof(skyjs_static_exts[0]));
}

const struct skyjs_static_ext *
skyjs_native_static_at(int index) {
\tif (index < 0 || index >= skyjs_native_static_count()) return NULL;
\treturn &skyjs_static_exts[index];
}
`;

    fs.mkdirSync(path.dirname(path.resolve(out)), { recursive: true });
    fs.writeFileSync(out, body);
    process.stdout.write("wrote " + out + " (" + entries.length + " entries)\n");
}

main();
